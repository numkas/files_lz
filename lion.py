#Для подсчета повторов
from collections import Counter

#Для работы с вордом
import docx

#Библиятека для гравиков
import matplotlib.pyplot as plt

#Открываем документ с текстом
d1 = docx.Document('lion.docx')  
#Пустую папку для таблицы
d2 = docx.Document() 
#Список для обзацев
t = [] 
#Алфавитик для проверки русских букв
a = ['а', 'б', 'в', 'г', 'д', 'е', 'ё', 'ж', 'з', 'и', 'й', 
'к', 'л', 'м', 'н', 'о', 'п', 'р', 'с', 'т', 'у', 'ф', 'х', 
'ц', 'ч', 'ш', 'щ', 'ь', 'ы', 'ъ', 'э', 'ю', 'я']  
#В нашу новую папку закидываем таблицу на 3 столбца
tb = d2.add_table(rows=1, cols=3) 
#Задаём первую ячейку для слов каторые мы должны проверить
h = tb.rows[0].cells  
#Наазвание дял первого столба
h[0].text = 'Слово'  
#Название второго столбы
h[1].text = 'Частота встречи, раз'  
#И третий
h[2].text = 'Частота встречи, %' 
#Этой командой мы превращаем наш текст в олдну общую строку
t = '\n'.join([p.text for p in d1.paragraphs]) 
#Этой командой наш текст мы превращаем вмаленкие буквы
tl = t.lower() 
#Этой командой мы делим слова пробелами
ws = tl.split() 
#Этим замудренным действием иы вроде как убираем все лишнее с текста кроме букв
fw = [w.strip(" ,.!?()[]{}'\"-_@") for w in ws if len(w) > 0 and all(c in a for c in w.strip(" ,.!?()[]{}'\"-_@"))] 
#Тут мы посчитывам сколько раз встречается определённое слово
wc = Counter(fw) 
#И сумируем 
tw = len(fw)
#Тут мы перебираем каждое слово и его количество
for w, k in wc.items():  
    #Для подсчета в процентиках
    pr = (k / tw) * 100  
    #Добавляем новую строку в таблицу для записи 
    nr = tb.add_row() 
    #И в эту ячейку закидываем наше слови и колисество и процентики
    nr.cells[0].text = w  
    nr.cells[1].text = str(k)  
    nr.cells[2].text = str(pr) 
#Сохраняем файл на диск
d2.save('table.docx') 
#А эта зумадрённая тема нам нужна что бы по буквенно разбить наши слова и считать их количество
ft = ''.join(filter(lambda x: 'а' <= x <= 'я', t.lower()))  
#Считаем
lc = Counter(ft) 
#Выставляем их по алфавиту
sl = sorted(lc.keys())  
#В алфавитном порядке распологаем количество наших подсчитаных букв
sc = [lc[l] for l in sl] 
#Размер для таблички
plt.figure(figsize=(10, 5))  
# Цвет столбов обводка и ширига
plt.bar(sl, sc, color='coral', edgecolor='black', width=0.6)  
#Пидпись нижней оси и размер шрифта
plt.xlabel('Буквы алфавита', fontsize=11) 
#Подмись левой оси и размер шрифта
plt.ylabel('Частота встречи, раз', fontsize=11)  
#Заголовок нашей таблицы
plt.title('Встречаемость букв в тексте', fontsize=13) 
#Сеточка - пунктирная и полуспрозрачная
plt.grid(axis='y', linestyle='--', alpha=0.7)  
#Выравнивание столбов
plt.tight_layout()  
#Вывод всей вот это шняги :(
plt.show()  

